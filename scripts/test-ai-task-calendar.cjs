const assert = require('node:assert/strict')
const { load } = require('./lib/ai-task-test-harness.cjs')
const { classifyTask, calendarEvents, timedLayout, spanLayout, moveCalendar, eventTime, onDay, calendarAttention } = load('_lib/calendar.ts')
const task = (id, fields = {}) => ({ id, title: id, groupId: 'group', parentId: null, startTime: null, deadline: null, status: 'todo', priority: 'normal', deletedAt: null, ...fields })
const at = (day, clock = '09:00') => `2026-09-${day}T${clock}:00+07:00`
assert.equal(classifyTask(task('empty')).kind, 'unscheduled')
assert.equal(classifyTask(task('invalid', { startTime: 'invalid' })).kind, 'unscheduled')
const deadline = classifyTask(task('deadline', { deadline: at(24) }))
assert.equal(deadline.kind, 'deadline'); assert.equal(deadline.start, '2026-09-24'); assert.equal(onDay(deadline, '2026-09-23'), false)
assert.equal(classifyTask(task('date', { startTime: '2026-09-20' })).kind, 'all-day')
assert.equal(classifyTask(task('legacy', { startTime: at(20), withinDay: true })).kind, 'all-day')
assert.equal(classifyTask(task('midnight', { startTime: at(20, '00:00') })).minute, 0)
const start = classifyTask(task('start', { startTime: at(20) }))
assert.equal(eventTime(start), '09:00'); assert.equal(start.endMinute, null)
const overnight = classifyTask(task('overnight', { startTime: at(20, '23:00'), deadline: at(21, '01:00') }))
assert.equal(overnight.kind, 'multi-day'); assert.equal(timedLayout([overnight]).length, 0)
assert.equal(classifyTask(task('utc', { startTime: '2026-09-19T18:00:00Z' })).start, '2026-09-20')
assert.deepEqual(calendarEvents([task('parent'), task('child', { parentId: 'parent' }), task('deleted', { deletedAt: at(20) }), task('done', { status: 'done' }), task('cancelled', { status: 'cancelled' })]).map(e => e.task.id), ['child', 'done', 'cancelled'])
assert.equal(calendarEvents([task('parent', { startTime: at(20) }), task('child', { parentId: 'parent' })]).length, 2)
const overlaps = timedLayout([start, classifyTask(task('overlap', { startTime: at(20, '09:15'), deadline: at(20, '11:00') })), classifyTask(task('later', { startTime: at(20, '12:00') }))])
assert.deepEqual(overlaps.map(e => e.columns), [2, 2, 1]); assert.notEqual(overlaps[0].column, overlaps[1].column)
const late = timedLayout([classifyTask(task('late', { startTime: at(20, '23:55') }))])[0]
assert.equal(late.top, 23 * 60 + 55); assert.equal(late.height, 44)
const span = classifyTask(task('span', { startTime: at(18), deadline: at(29) }))
const clipped = spanLayout([span], ['2026-09-21', '2026-09-22', '2026-09-23', '2026-09-24', '2026-09-25', '2026-09-26', '2026-09-27'])[0]
assert.equal(clipped.start, 0); assert.equal(clipped.end, 6)
assert.equal(moveCalendar('2026-01-31', 'month', 1), '2026-02-01')
assert.equal(moveCalendar('2026-12-31', 'day', 1), '2027-01-01')
assert.equal(calendarAttention(task('done', { status: 'done', deadline: at(20) }), Date.parse(at(25))), '')
console.log('PASS: calendar classification, Vietnam timezone, hierarchy, statuses, overlap lanes, week clipping and navigation')
